class RussianNER:
    def __init__(self):
        self.nlp = spacy.load("ru_core_news_sm")

    def extract(self, text: str) -> List[str]:
        entities = []
        text_lower = text.lower()

        # 1. Dictionary matching (domain entities) — только по границам слов,
        # иначе короткие термины ("ци", "ша", "лев") матчатся как подстроки
        for term in DOMAIN_ENTITIES:
            if re.search(rf"(?<!\w){re.escape(term)}(?!\w)", text_lower):
                entities.append(term)

        # 2. spaCy NER + lemmatization
        doc = self.nlp(text)
        for ent in doc.ents:
            name = ent.text.lower().strip()
            # Try to lemmatize the entity text (use first token's lemma as base)
            first_lemma = ent[0].lemma_.lower() if len(ent) > 0 else name
            if is_valid_entity(first_lemma) and len(first_lemma) >= 3:
                entities.append(first_lemma)
            elif is_valid_entity(name) and len(name) >= 3:
                entities.append(name)

        # 3. spaCy lemmatization + POS: extract ONLY meaningful nouns (NOUN, PROPN)
        # Исключаем ADJ (прилагательные), VERB (глаголы), ADV (наречия) — они создают шум
        stop_lemmas = {
            "который",
            "этот",
            "такой",
            "весь",
            "мочь",
            "быть",
            "иметь",
            "являться",
            "сделать",
            "получить",
            "стать",
            "находиться",
            "говорить",
            "знать",
            "хотеть",
            "думать",
            "смотреть",
            "один",
            "два",
            "три",
            "первый",
            "второй",
            "последний",
            "каждый",
            "любой",
            "некоторый",
            "другой",
            "самый",
            "большой",
            "маленький",
            "новый",
            "старый",
            "хороший",
            "плохой",
            "важный",
            "главный",
            "разный",
            "свой",
        }
        for token in doc:
            lemma = token.lemma_.lower().strip()
            if len(lemma) < 4 or not is_valid_entity(lemma):
                continue
            if lemma in stop_lemmas:
                continue
            # Только существительные (NOUN) и имена собственные (PROPN)
            if token.pos_ in ("NOUN", "PROPN"):
                entities.append(lemma)

        # Deduplicate while preserving order
        seen = set()
        unique = []
        for e in entities:
            if e not in seen:
                seen.add(e)
                unique.append(e)

        return unique
